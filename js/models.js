  const C = (x, y, r) => ({ t: 'c', x, y, r });
  const P = pts => ({ t: 'p', pts });
  const L = (pts, w, dash) => ({ t: 'l', pts, w, dash });
  const M = (x1, x2, y, h, a) => ({ t: 'm', x1, x2, y, h, a });
  const col = (x, y0, y1, w) => R(x - w / 2, y0, w, y1 - y0);
  // 镜像（对称构架）：返回 x' = 2*cx - x 的几何
  function mirG(g, cx) {
    const mx = x => 2 * cx - x;
    switch (g.t) {
      case 'r': return R(mx(g.x + g.w), g.y, g.w, g.h, g.cls);
      case 'c': return C(mx(g.x), g.y, g.r);
      case 'p': return P(g.pts.map(p => [mx(p[0]), p[1]]));
      case 'l': return L(g.pts.map(p => [mx(p[0]), p[1]]), g.w, g.dash);
      case 'm': return M(mx(g.x2), mx(g.x1), g.y, g.h, g.a);
    }
  }
  function mirror(parts, cx, keepLab) {
    const out = [];
    parts.forEach(p => {
      out.push(p);
      if (p.sym === false) return;
      const q = Object.assign({}, p, { id: p.id + '_r', g: p.g.map(g => mirG(g, cx)), lab: null });
      if (p.ex) q.ex = [-p.ex[0], p.ex[1]];
      if (keepLab && keepLab[p.id]) q.lab = keepLab[p.id];
      out.push(q);
    });
    return out;
  }
  const withR = ids => ids.flatMap(i => [i, i + '_r']);
  // 屋面带：沿椽线上方 a..b 偏移
  function roofBand(line, a, b) {
    const top = line.map(p => [p[0], p[1] + b]), bot = line.map(p => [p[0], p[1] + a]).reverse();
    return P(top.concat(bot));
  }
  /* 《营造法式》卷五"举折之制"：
   * 先定举高 H（撩檐方背至脊槫背）；第一缝（上平槫）自脊至撩檐直线下折 H/10，
   * 第二缝自所折点至撩檐再连直线下折 H/20，以下每缝减半。返回各缝槫心高度。 */
  function juzhe(xE, yE, xRidge, H, xs) { // xs：自脊向檐依次的槫位（不含脊、撩檐）
    const out = { [xRidge]: yE + H };
    let ux = xRidge, uy = yE + H, drop = H / 10;
    xs.forEach(x => {
      const t = (x - xE) / (ux - xE);
      const y = yE + (uy - yE) * t - drop;
      out[x] = y; ux = x; uy = y; drop /= 2;
    });
    return out;
  }

